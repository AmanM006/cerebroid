"""Centralized app settings, read once from environment variables.

Kept as a single pydantic-settings object so every module reads config the
same way instead of calling os.environ directly all over the codebase.
"""
import os
import tempfile
from functools import lru_cache
from pathlib import Path
import secrets

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    # .env is looked up in the working directory and its parent, so the repo-root
    # .env is found whether commands run from the root or from backend/.
    model_config=SettingsConfigDict(env_file=(".env", "../.env"), extra="ignore")

    app_env: str="development"
    log_level: str="INFO"
    # Precompute demo-case profiles in the background after start-up (see app/services/warmup.py).
    warmup_profiles: bool=True
    # Create the demo cases and test accounts when the app starts (idempotent; off in tests).
    seed_on_startup: bool=True
    # Largest request body accepted (bytes); every current endpoint takes small JSON at most.
    max_body_bytes: int=1_000_000
    # Login attempts allowed per client IP per window (generous: evaluators share few IPs).
    login_rate_limit: int=30
    login_rate_window_seconds: int=300
    # Analysis requests per signed-in user and client IP per window (one case view makes about 10).
    analysis_rate_limit: int=300
    analysis_rate_window_seconds: int=60
    # Heavy computations (uncached profiles, tipping sweeps) allowed at once, and how long a request
    # waits for a free slot before getting 503 SERVER_BUSY.
    heavy_concurrency: int=2
    heavy_wait_seconds: float=20.0
    # MRI uploads: where they are processed and kept, size, rate and retention limits.
    upload_dir: str=""
    upload_max_body_bytes: int=150_000_000
    upload_rate_limit: int=10
    upload_rate_window_seconds: int=3600
    upload_max_per_user: int=10
    upload_ttl_hours: int=24
    upload_timeout_seconds: int=240
    cors_origins: str="http://localhost:5173"

    database_url: str = Field(
        default_factory=lambda: (
            os.environ.get("DATABASE_URL")
            or os.environ.get("INTERNAL_DATABASE_URL")
            or os.environ.get("POSTGRESQL_URL")
            or ("sqlite:////tmp/vbx.db" if os.environ.get("RENDER") else "postgresql+psycopg://vbx:vbx@localhost:5432/vbx")
        )
    )

    # Secure 48-byte token generated by default if not passed in environment
    jwt_secret_key: str=Field(default_factory=lambda: secrets.token_urlsafe(48), min_length=32)
    jwt_access_token_ttl_minutes: int=Field(default=15, ge=1, le=15)
    jwt_refresh_token_ttl_days: int=Field(default=7, ge=1, le=30)

    # Repository root (holds artifacts/ and ml/configs/). The container mirrors the repo layout.
    repo_root: Path=Field(default_factory=lambda: Path(__file__).resolve().parents[3])

    # Built frontend (frontend/dist) to serve from the API itself, for single-service hosting.
    # Unset in docker compose, where nginx serves the frontend.
    frontend_dist: Path | None=None

    login_max_failed_attempts: int=Field(default=5, ge=1)
    login_lockout_minutes: int=Field(default=15, ge=1)

    @field_validator("database_url")
    @classmethod
    def _psycopg_driver(cls, value: str) -> str:
        """Hosts hand out postgres:// or postgresql:// URLs; SQLAlchemy needs the psycopg 3 driver named."""
        if os.environ.get("RENDER") and "127.0.0.1" in value:
            # On Render, 127.0.0.1 is not reachable unless a local container exists; fallback to sqlite
            return "sqlite:////tmp/vbx.db"
        for prefix in ("postgres://", "postgresql://"):
            if value.startswith(prefix):
                return "postgresql+psycopg://"+value[len(prefix):]
        return value

    @field_validator("jwt_secret_key")
    @classmethod
    def _reject_placeholder_secret(cls, value: str) -> str:
        if "change-me" in value:
            raise ValueError("JWT_SECRET_KEY is still the .env.example placeholder")
        return value

    @property
    def cors_origin_list(self) -> list[str]:
        return [o.strip() for o in self.cors_origins.split(",") if o.strip()]

    @property
    def artifacts_root(self) -> Path:
        return self.repo_root/"artifacts"

    @property
    def feature_table_path(self) -> Path:
        return self.artifacts_root/"features"/"features.parquet"

    @property
    def volumes_root(self) -> Path:
        return self.artifacts_root/"volumes"

    @property
    def uploads_root(self) -> Path:
        """Uploaded studies live here (temporary; purged after upload_ttl_hours)."""
        return Path(self.upload_dir) if self.upload_dir else Path(tempfile.gettempdir())/"cerebroid-uploads"

    @property
    def markers_config_path(self) -> Path:
        return self.repo_root/"ml"/"configs"/"markers.yaml"

    @property
    def is_production(self) -> bool:
        return self.app_env=="production"


@lru_cache
def get_settings() -> Settings:
    return Settings()
